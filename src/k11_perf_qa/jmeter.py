"""Import JMeter results (JTL) so existing JMeter test plans produce the same evidence.

JMeter writes results as CSV (the default, with a header row) or XML. Each sample becomes a
request for the endpoint named by its sampler label (name samplers like "GET /orders/{id}" to
match API flows and SLO patterns). Transaction Controller samples are skipped, since they sum
their children. Load was generated by JMeter, so k11 guardrails didn't apply; only the analysis
does: per-endpoint latency, SLOs, regressions against a baseline, findings for the Release Gate.

    CSV: timeStamp,elapsed,label,responseCode,responseMessage,threadName,...,success,...,allThreads,...
    XML: <testResults><httpSample t="12" ts="..." lb="GET /x" rc="200" s="true" na="4"/>...</testResults>
"""

from __future__ import annotations

import csv
import xml.etree.ElementTree as ET
from datetime import datetime, timezone
from pathlib import Path

from .engine import MAX_EXAMPLES, RunResult

TRANSACTION = "Number of samples in transaction"
NEEDED = {"timeStamp", "elapsed", "label", "success"}


class JtlError(ValueError):
    pass


def _code(rc: str) -> int:
    rc = (rc or "").strip()
    return int(rc) if rc.isdigit() else 0  # "Non HTTP response code: ..." = connection failure


def _rows_csv(path: Path):
    with path.open(newline="", encoding="utf-8-sig", errors="replace") as fh:
        reader = csv.DictReader(fh)
        missing = NEEDED - set(reader.fieldnames or [])
        if missing:
            raise JtlError(f"{path.name}: not a JMeter CSV with a header row (missing {sorted(missing)}); "
                           "set jmeter.save.saveservice.print_field_names=true")
        for r in reader:
            if (r.get("responseMessage") or "").startswith(TRANSACTION):
                continue
            yield {"ts": int(float(r["timeStamp"])), "elapsed": float(r["elapsed"]), "label": r["label"],
                   "rc": r.get("responseCode", ""), "ok": str(r["success"]).strip().lower() == "true",
                   "threads": int(float(r.get("allThreads") or 0) or 0), "message": r.get("failureMessage") or r.get("responseMessage") or ""}


def _rows_xml(path: Path):
    try:
        root = ET.parse(path).getroot()
    except ET.ParseError as e:
        raise JtlError(f"{path.name}: invalid XML: {e}") from None
    if root.tag != "testResults":
        raise JtlError(f"{path.name}: not a JMeter XML results file (<testResults>)")
    for el in root:
        children = [c for c in el if c.tag in ("httpSample", "sample")]
        is_tx = (el.get("rm") or "").startswith(TRANSACTION) or (el.tag == "sample" and children and not el.get("rc"))
        for s in (children if is_tx else [el]):
            if s.tag not in ("httpSample", "sample"):
                continue
            fm = s.find("failureMessage") if s.find("failureMessage") is not None else s.find("assertionResult/failureMessage")
            yield {"ts": int(s.get("ts", 0)), "elapsed": float(s.get("t", 0)), "label": s.get("lb", ""),
                   "rc": s.get("rc", ""), "ok": s.get("s", "true").lower() == "true", "threads": int(s.get("na", 0) or 0),
                   "message": (fm.text if fm is not None and fm.text else s.get("rm", "")) or ""}


def load_jtl(path: Path, scenario: str, environment: str) -> RunResult:
    path = Path(path)
    if not path.is_file():
        raise JtlError(f"Results file not found: {path}")
    head = path.read_text("utf-8", errors="replace")[:200].lstrip()
    rows = _rows_xml(path) if head.startswith("<") else _rows_csv(path)
    res = RunResult("completed", environment, scenario, "jmeter", {})
    first = last = None
    max_threads = 0
    n = 0
    starts: list[tuple[int, bool]] = []
    try:
        for r in rows:
            n += 1
            ep = r["label"] or "(unnamed sampler)"
            code = _code(r["rc"])
            start, end = r["ts"], r["ts"] + r["elapsed"]
            first = start if first is None else min(first, start)
            last = end if last is None else max(last, end)
            max_threads = max(max_threads, r["threads"])
            res.codes[ep][code] += 1
            if code:
                res.samples[ep].append(r["elapsed"])
            if code >= 500:
                res.server_errors[ep] += 1
            if not r["ok"]:
                res.errors[ep] += 1
                if len(res.examples) < MAX_EXAMPLES:
                    res.examples.append({"endpoint": ep, "status": code or None, "error": str(r["message"])[:200]})
            starts.append((start, not r["ok"]))
    except (KeyError, ValueError) as e:
        raise JtlError(f"{path.name}: unreadable row {n}: {e}") from None
    if not n:
        raise JtlError(f"{path.name}: no samples")
    for start, failed in starts:
        t = res.timeline[int((start - first) / 1000)]
        t[0] += 1
        t[1] += int(failed)
    res.duration_s = round(max((last - first) / 1000, 0.001), 2)
    res.started_at = datetime.fromtimestamp(first / 1000, timezone.utc).isoformat(timespec="seconds")
    res.profile = {"vus": max_threads or None, "duration_s": res.duration_s, "ramp_up_s": None,
                   "think_time_ms": None, "max_rps": None, "source": path.name}
    res.flows = [{"file": path.name, "name": "JMeter test plan results", "weight": 1}]
    res.notes.append(f"Imported from JMeter results ({path.name}, {n} samples); load was generated by JMeter, "
                     "so k11 guardrails did not apply.")
    return res
